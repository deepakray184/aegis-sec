"""
Markdown Reporter for AegisSec.
"""

from aegis_core.models import AuditResult, Severity


class MarkdownReporter:
    def __init__(self, result: AuditResult):
        self.result = result

    def render(self) -> str:
        r = self.result
        t = r.target
        s = r.summary

        lines = [
            f"# 🛡️ Security Audit Report: {t.domain}",
            "",
            f"> **Generated by AegisSec Website Security Auditor**  ",
            f"> **Scan Date:** {t.scan_timestamp} | **Duration:** {s.duration_seconds}s | **Target:** `{t.url}`",
            "",
            "---",
            "",
            "## 📊 Executive Summary",
            "",
            f"| Metric | Value |",
            f"| :--- | :--- |",
            f"| **Overall Security Score** | **{s.score} / 100** |",
            f"| **Security Grade** | **`{s.grade}`** ({s.grade_label}) |",
            f"| **Critical Vulnerabilities** | **{s.critical_count}** 🔴 |",
            f"| **High Severity Issues** | **{s.high_count}** 🟠 |",
            f"| **Medium Severity Issues** | **{s.medium_count}** 🟡 |",
            f"| **Low / Info Notices** | **{s.low_count + s.info_count}** 🔵 |",
            f"| **Server Detected** | `{t.server_banner or 'Masked / Hidden'}` |",
            f"| **IP Addresses** | `{', '.join(t.ip_addresses) or 'N/A'}` |",
            f"| **Network / ASN** | `{t.asn or t.isp or 'N/A'} ({t.city or ''}, {t.country or ''})` |",
            f"| **Open Ports (Shodan)** | `{', '.join(map(str, t.open_ports)) if t.open_ports else 'None listed'}` |",
            "",
            "### OWASP Top 10 Distribution",
            "",
        ]

        if s.owasp_breakdown:
            for cat, cnt in s.owasp_breakdown.items():
                lines.append(f"- **{cat}**: {cnt} finding(s)")
        else:
            lines.append("_No OWASP Top 10 vulnerabilities detected._")

        lines.extend([
            "",
            "---",
            "",
            "## 🔍 Detailed Security Findings",
            "",
        ])

        if not r.findings:
            lines.append("🎉 **No security issues found! The target demonstrated an exemplary security posture.**\n")
        else:
            for i, f in enumerate(r.findings, 1):
                badge = {
                    Severity.CRITICAL: "🔴 CRITICAL",
                    Severity.HIGH: "🟠 HIGH",
                    Severity.MEDIUM: "🟡 MEDIUM",
                    Severity.LOW: "🔵 LOW",
                    Severity.INFO: "⚪ INFO",
                }.get(f.severity, f.severity.value)

                lines.extend([
                    f"### {i}. [{badge}] {f.title}",
                    "",
                    f"- **ID:** `{f.id}` | **Category:** {f.category.value}",
                    f"- **OWASP:** {f.owasp_category or 'N/A'} | **CWE:** {f.cwe_id or 'N/A'} | **CVSS:** {f.cvss_score or 'N/A'}",
                    "",
                    f"#### Description",
                    f"{f.description}",
                    "",
                    f"#### Security Impact",
                    f"{f.impact}",
                    "",
                ])

                if f.evidence:
                    lines.extend([
                        f"#### Evidence",
                        "```http",
                        f.evidence,
                        "```",
                        "",
                    ])

                lines.extend([
                    f"#### Remediation",
                    f"{f.remediation}",
                    "",
                ])

                if f.remediation_code:
                    lines.append("##### Remediation Code Snippets")
                    for srv, code in f.remediation_code.items():
                        lines.extend([
                            f"**{srv}:**",
                            "```nginx" if "nginx" in srv.lower() else "```apache" if "apache" in srv.lower() else "```javascript" if "express" in srv.lower() else "```text",
                            code,
                            "```",
                            "",
                        ])

                lines.append("---")
                lines.append("")

        return "\n".join(lines)

    def save(self, filepath: str) -> None:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(self.render())
